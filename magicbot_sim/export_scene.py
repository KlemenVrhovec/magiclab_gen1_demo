"""
Export the simulation scene (robot + table + box) as a standalone MuJoCo MJCF folder.

    python export_scene.py                      # writes exports/magicbot_scene/ and a .zip
    python export_scene.py --out-dir some/dir   # anywhere else
    python export_scene.py --palm-pads          # include the palm pads (flip_box uses them)

WHY. Every script here builds its scene in memory: pick_box.build_model loads the official
MAGICBOT.xml, welds the pelvis to the world and adds the table and the box to an MjSpec.
Nothing on disk contains that scene, so someone without this repo's Python cannot open it.
This writes it out as plain XML next to a copy of the meshes, so it loads with nothing but
MuJoCo:

    python -m mujoco.viewer --mjcf exports/magicbot_scene/scene_pick_box.xml

Two scenes are written, the ones the grasp scripts actually use:
  scene_pick_box.xml   9 x 9 x 20 cm block, 0.30 kg (pick_box.py, v2, v3, rotate_*)
  scene_big_box.xml    20 x 27 x 27 cm box (pick_box_v4.py, export_robot_plan.py)

Each export is reloaded from disk and checked against the in-memory model (same body,
geom, joint and actuator counts, same state after 1 s of passive simulation), so what is
sent is what the scripts simulate.
"""

import argparse
import shutil
from pathlib import Path

import mujoco
import numpy as np

import pick_box
import pick_box_v4 as v4
from pick_box import build_model

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE / "exports" / "magicbot_scene"
MESHES = HERE / "magicbot-gen1_description" / "meshes"

SCENES = {
    "scene_pick_box": dict(),
    "scene_big_box": dict(box_half=v4.BIG_BOX_HALF, box_y=v4.BIG_BOX_Y),
}


def build_with_spec(palm_pads, **kw):
    """build_model, keeping hold of the MjSpec it compiled (spec_hook sees the same object)."""
    held = []
    model = build_model(palm_pads=palm_pads, spec_hook=held.append, **kw)
    return held[0], model


def passive_state(model, seconds=1.0):
    data = mujoco.MjData(model)
    mujoco.mj_resetData(model, data)
    for _ in range(int(seconds / model.opt.timestep)):
        mujoco.mj_step(model, data)
    return data.qpos.copy()


def check(xml_path, ref):
    got = mujoco.MjModel.from_xml_path(str(xml_path))
    for f in ("nbody", "ngeom", "njnt", "nu", "nq", "nmesh"):
        if getattr(got, f) != getattr(ref, f):
            raise SystemExit(f"{xml_path.name}: {f} {getattr(got, f)} != {getattr(ref, f)}")
    err = np.abs(passive_state(got) - passive_state(ref)).max()
    if err > 1e-6:
        raise SystemExit(f"{xml_path.name}: reloaded model diverges, max |dq| = {err:.2e}")
    return got, err


README = """\
# MagicBot Gen1 - simulation scene (MuJoCo)

Standalone export of the scene used by the MagicBot Gen1 grasp simulations: the robot,
a fixed table and a free box. Plain MJCF + STL meshes; nothing but MuJoCo is needed.
Generated by `magicbot_sim/export_scene.py` (MuJoCo {mujoco_version}).

## Open it

```
pip install mujoco
python -m mujoco.viewer --mjcf scene_pick_box.xml
```

```python
import mujoco
model = mujoco.MjModel.from_xml_path("scene_pick_box.xml")
data = mujoco.MjData(model)
```

## Files

| file | contents |
|---|---|
| `scene_pick_box.xml` | box {small_box} m, {box_mass} kg, centre at y = {small_y} m |
| `scene_big_box.xml`  | box {big_box} m, {box_mass} kg, centre at y = {big_y} m |
| `meshes/`            | robot STL meshes (unchanged from magicbot-gen1_description) |
| `LICENSE`            | BSD-3 licence of the robot model (Magiclab Robotics) |

## What is in the scene

World frame: z up, the robot faces -y (the table is in front of it at negative y).

- **Robot**: the official `MAGICBOT.xml` from magicbot-gen1_description, with one change:
  the pelvis free joint is removed and the pelvis is welded to the world at
  z = {pelvis_h} m. The robot cannot fall or walk; only the joints move.
  {njnt_robot} hinge joints (legs, waist, head, 7 per arm). The arms end at the wrist:
  there are **no fingers** in this model, grasps are two-handed pinches between the palms.
- **Actuators**: {nu} `general` actuators, one per joint, gain 1 -> `data.ctrl` is joint
  **torque** in N*m. The scripts track joint targets with a gravity-compensated PD in
  Python; there is no position servo inside the model.
- **Table**: fixed box, top at z = {table_top} m, {table_x} x {table_y} m, centred at
  y = {table_cy} m.
- **Box**: free body resting on the table, friction {friction}.
- **Physics**: timestep {timestep} s, elliptic friction cones, impratio {impratio}. The
  impratio matters: with MuJoCo's defaults a squeezed box slowly slides out of the grip.
- **Palm pads**: {pads}.
- Sensors: IMU (accelerometer + gyro) at the pelvis, as in the original model.

## Limits

- This is the simulation model, not the real P5. The arm joints match the real robot's
  joint_la1..7 / ra1..7 in order and axes, but the waist sits ~21 mm higher than on the
  real robot, so the same joint angles put the hands ~2 cm higher here.
- Joint position limits are those of the original MJCF (all joints have damping 20).
  The actuators have **no torque limits**, and real-robot velocity and acceleration
  limits are not in the model either; a controller has to enforce them itself.
- The table and box sizes are the ones chosen for the simulation (reachable with the
  pelvis at {pelvis_h} m), not measured from a real setup.
"""


def write_readme(out, models, palm_pads):
    small, big = models["scene_pick_box"], models["scene_big_box"]
    dims = lambda m: " x ".join(f"{2 * s:.2f}" for s in m.geom("box_geom").size)
    table = small.geom("table_geom")
    text = README.format(
        mujoco_version=mujoco.__version__,
        small_box=dims(small), big_box=dims(big), box_mass=pick_box.BOX_MASS,
        small_y=small.body("box").pos[1], big_y=big.body("box").pos[1],
        pelvis_h=pick_box.PELVIS_H, njnt_robot=small.njnt - 1, nu=small.nu,
        table_top=pick_box.TABLE_TOP, table_x=2 * table.size[0], table_y=2 * table.size[1],
        table_cy=small.body("table").pos[1], friction=pick_box.BOX_FRICTION,
        timestep=small.opt.timestep, impratio=pick_box.IMPRATIO,
        pads="included (flat box geoms in each palm)" if palm_pads else
             "not included (re-export with --palm-pads for them)",
    )
    (out / "README.md").write_text(text, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--palm-pads", action="store_true",
                    help="add the flat palm pad geoms (see pick_box.PALM_PADS)")
    ap.add_argument("--no-zip", action="store_true")
    args = ap.parse_args()

    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    # only the meshes the scene references: the description folder also holds the finger
    # meshes of MAGICBOT_with_hand.urdf, which this model has no bodies for (~17 MB)
    if (out / "meshes").exists():
        shutil.rmtree(out / "meshes")
    (out / "meshes").mkdir()
    shutil.copy(MESHES.parent / "LICENSE", out / "LICENSE")

    models = {}
    for name, kw in SCENES.items():
        spec, model = build_with_spec(args.palm_pads, **kw)
        spec.modelname = name
        for mesh in spec.meshes:
            shutil.copy(MESHES / mesh.file, out / "meshes" / mesh.file)
        # to_xml recompiles against the spec's own folder, so the mesh path can only be
        # repointed in the text afterwards
        xml = spec.to_xml().replace(f'meshdir="{spec.meshdir}"', 'meshdir="meshes/"')
        path = out / f"{name}.xml"
        path.write_text(xml, encoding="utf-8")
        got, err = check(path, model)
        box = got.geom("box_geom")
        print(f"{path.name}: {got.nbody} bodies, {got.njnt} joints, {got.nu} actuators, "
              f"box {2 * box.size[0]:.2f} x {2 * box.size[1]:.2f} x {2 * box.size[2]:.2f} m, "
              f"reload ok (max |dq| {err:.1e})")
        models[name] = got
    write_readme(out, models, args.palm_pads)

    if not args.no_zip:
        z = shutil.make_archive(str(out), "zip", root_dir=out.parent, base_dir=out.name)
        print(f"zip: {z}")
    print(f"pelvis {pick_box.PELVIS_H} m, table top {pick_box.TABLE_TOP} m, "
          f"palm pads {'on' if args.palm_pads else 'off'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
